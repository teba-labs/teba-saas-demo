import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const source=await readFile(new URL('../../modules/dashboard/financial-import-engine.js',import.meta.url),'utf8');
const engine=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const headers=['الشهر','الإيرادات','المصروفات','عدد الحالات','عدد التحاليل','الفرع'];
const mapping=engine.suggestFinancialMapping(headers);
assert.equal(mapping.find(x=>x.header==='الشهر').fieldKey,'period_date');
assert.equal(mapping.find(x=>x.header==='الإيرادات').fieldKey,'revenue');
assert.equal(mapping.find(x=>x.header==='المصروفات').fieldKey,'expenses');
assert.equal(mapping.find(x=>x.header==='عدد الحالات').fieldKey,'cases');
assert.equal(mapping.find(x=>x.header==='عدد التحاليل').fieldKey,'tests_count');
assert.equal(mapping.find(x=>x.header==='الفرع').fieldKey,'branch_name');
const analysis=engine.analyzeFinancialRows({headers,rows:[['2023-02',900,300,18,45,'فرع ألف'],['2024-01',1000,400,20,50,'فرع ألف']],mapping});
assert.equal(analysis.ready,true);
assert.equal(analysis.records.length,8);
assert.equal(analysis.duplicateRows,0);
const report=engine.buildGenericHistoricalReport(analysis.records.map(x=>({...x,branch_id:'branch-a'})));
assert.equal(report.totals.revenue,1900);
assert.equal(report.totals.expenses,700);
assert.equal(report.totals.cases,38);
assert.equal(report.totals.tests,95);
assert.equal(report.totals.profit,1200);
assert.equal(report.monthly.length,2);
assert.equal(report.monthlyPlan.month,'2024-02');
assert.equal(report.monthlyPlan.revenue,900);
assert.equal(report.monthlyPlan.cases,18);
assert.equal(report.monthlyPlan.years,1);
const splitHeaders=['السنة','الشهر','الإيرادات','المصروفات'];
const splitMapping=engine.suggestFinancialMapping(splitHeaders);
assert.equal(splitMapping.find(x=>x.header==='السنة').fieldKey,'year');
assert.equal(splitMapping.find(x=>x.header==='الشهر').fieldKey,'month');
const split=engine.analyzeFinancialRows({headers:splitHeaders,mapping:splitMapping,rows:[[2022,7,1500,600],[2023,7,1800,700]]});
assert.equal(split.ready,true);
assert.equal(split.records[0].period_date,'2022-07-01');
assert.equal(split.records[2].period_date,'2023-07-01');
const excelSerial=engine.normalizeFinancialDate(45292);
assert.equal(excelSerial,'2024-01-01');
const normalizedHeaders=['التاريخ','نوع الحركة','المبلغ','العدد','اسم التحليل','تكلفة الوحدة','سعر البيع'];
const normalizedMapping=engine.suggestFinancialMapping(normalizedHeaders);
const normalized=engine.analyzeFinancialRows({headers:normalizedHeaders,mapping:normalizedMapping,rows:[['2024-01-15','الإيرادات',1200,'','','',''],['2024-01-15','المصروفات',500,'','','',''],['2024-01-15','عدد الحالات','',24,'','',''],['2024-01-15','تحليل CBC',100,1,'CBC',35,100]]});
assert.equal(normalized.ready,true);
const normalizedReport=engine.buildGenericHistoricalReport(normalized.records);
assert.equal(normalizedReport.totals.revenue,1200);
assert.equal(normalizedReport.totals.expenses,500);
assert.equal(normalizedReport.totals.cases,24);
assert.equal(normalizedReport.items[0].name,'CBC');
assert.equal(normalizedReport.items[0].profit,65);
const duplicate=engine.analyzeFinancialRows({headers,mapping,rows:[['2024-01',100,50,10,20,'A'],['2024-01',100,50,10,20,'A']]});
assert.equal(duplicate.duplicateRows,4);
console.log('PASS generic financial workbook import: wide and normalized layouts, date parsing, duplicates, P&L, test profitability and seasonal monthly plan');
