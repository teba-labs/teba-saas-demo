import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const root = new URL('../../', import.meta.url);
const repository = await readFile(new URL('dashboard/repository.js', root), 'utf8');
const dashboard = await readFile(new URL('assets/js/dashboard.js', root), 'utf8');
const html = await readFile(new URL('app/dashboard.html', root), 'utf8');
assert.match(repository, /export async function getOwnerTestRangeReport/);
assert.match(repository, /\.eq\('tenant_id',tenantId\)/);
assert.match(repository, /\.gte\('visit_work_date',fromDate\)/);
assert.match(repository, /\.lt\('visit_work_date',toDateExclusive\)/);
assert.match(repository, /\.neq\('status','cancelled'\)/);
assert.match(repository, /offset\+=500/);
assert.match(repository, /visit_tests/);
assert.match(dashboard, /getOwnerTestRangeReport/);
assert.match(dashboard, /runTestRangeReport/);
assert.match(dashboard, /toDateExclusive/);
assert.match(html, /testRangeFrom/);
assert.match(html, /testRangeTo/);
assert.match(html, /testRangeRows/);
console.log('PASS: date-range test report is tenant/branch scoped, paginated and excludes cancelled visits/tests.');
