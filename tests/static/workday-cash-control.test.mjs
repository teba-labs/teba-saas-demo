import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'../..');
const page=fs.readFileSync(path.join(root,'app/workday.html'),'utf8');
const script=fs.readFileSync(path.join(root,'assets/js/workday.js'),'utf8');
const repo=fs.readFileSync(path.join(root,'modules/workday/repository.js'),'utf8');
const sql=fs.readFileSync(path.join(root,'database/migrations/005_workday_cash_control.sql'),'utf8');
test('workday page is Arabic RTL and includes open, close, expense and cash summary controls',()=>{
  assert.match(page,/lang="ar" dir="rtl"/);
  for(const id of ['workDate','openDay','closeDay','category','amount','addExpense','collected','expenses','net','movements']) assert.match(page,new RegExp(`id="${id}"`));
});
test('workday actions are called through scoped RPC contracts and active staff selection',()=>{
  assert.match(script,/openWorkday\(/); assert.match(script,/closeWorkday\(/); assert.match(script,/addWorkdayExpense\(/);
  assert.match(script,/staffId:staffId\(\)/); assert.match(script,/tenantId:state\.tenant\.id,branchId:state\.branch\.id/);
});
test('closing requires explicit confirmation and refreshes immutable closing snapshot display',()=>{
  assert.match(script,/if\(!confirm\(prompt\)\)return/); assert.match(script,/getLatestClosing/); assert.match(script,/closing_snapshot/);
});
test('expense and payment movements require an open workday and are assigned to its date',()=>{
  assert.match(sql,/Open the branch workday before recording a payment/);
  assert.match(sql,/Open the branch workday before recording an expense/);
  assert.match(sql,/workday_id/); assert.match(sql,/v_work_date/);
  assert.match(sql,/create or replace function public\.create_visit_intake/);
  assert.match(sql,/create or replace function private\.assign_open_workday_to_visit/);
  assert.match(sql,/limit 1 for update/);
});
test('cash ledger is generated by database triggers and cannot be edited from the UI',()=>{
  assert.match(sql,/create or replace function private\.add_payment_to_ledger/);
  assert.match(sql,/create or replace function private\.add_expense_to_ledger/);
  assert.match(repo,/from\(TABLES\.ledger\)/);
  assert.doesNotMatch(script,/from\(['"]financial_ledger['"]\)\.(insert|update|delete)/);
});

test('expired workdays auto-close only after the local sync queue is empty and the app is online',()=>{
  assert.match(script,/workday\.work_date<localDate\(\)/);
  assert.match(script,/timeZone:zone/);
  assert.match(script,/navigator\.onLine===false/);
  assert.match(script,/getOutboxSummary\(/);
  assert.match(script,/if\(pending\.total\)/);
  assert.match(script,/تم إغلاق يوم العمل السابق تلقائيًا/);
  assert.match(script,/setInterval\(/);
});
